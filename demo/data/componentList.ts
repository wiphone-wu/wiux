export interface ComponentCategory {
  name: string;
  name_zh: string;
  items: ComponentListItem[];
}

export function getCategories(): ComponentCategory[] {
  const grouped = new Map<string, ComponentListItem[]>();

  for (const item of componentList) {
    const key = item.category_en;
    if (!grouped.has(key)) {
      grouped.set(key, []);
    }
    grouped.get(key)!.push(item);
  }

  return Array.from(grouped, ([name, items]) => ({
    name,
    name_zh: items[0].category_cn,
    items,
  }));
}

export function getComponent(name: string): ComponentListItem | undefined {
  return componentList.find((c) => c.name === name);
}

export function getComponentNames(): string[] {
  return componentList.map((c) => c.name);
}

export default componentList;
